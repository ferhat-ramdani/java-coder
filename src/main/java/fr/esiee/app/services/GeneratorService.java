@Tag(name = "Generator", description = "endpoints to use generator")
@Path("/api/gen")
public class GeneratorService implements HttpService {

  private static final Logger LOGGER = LoggerFactory.getLogger(GeneratorService.class);
  private static final String SYSTEM_ERR_MESSAGE = "Here are the compilation errors, correct them.";
  private final DbManager dbService;
  private final LLMConfig llmConfig;
  private final int NB_ATTEMPTS = 3;
  private final int MAX_MEMORY_PROMPTS = 30;

  private LLM curLLM;
//  private OllamaChatModel model;
  private OllamaStreamingChatModel model;
  private Assistant assistant;

  public GeneratorService() {
    this.dbService = Contexts.globalContext().get(DbManager.class).orElseThrow(() -> new NoSuchElementException("DbManager not found."));
    this.llmConfig = Contexts.globalContext().get(LLMConfig.class).orElse(LLMConfig.defaultConfig());
  }

  private record ClassResponse(String code, boolean compile) {}

  @Override
  public void routing(HttpRules rules) {
    rules.post("/class", Handler.create(Prompt.class, this::generateClass))
            .post("/exec", Handler.create(Integer.class, this::executeClass));
  }

  @POST
  @javax.ws.rs.Path("/class")
  @Operation(summary = "generate a class", description = "Retrieves a class generated by llm")
  @Consumes("application/json")
  @ApiResponse(content = @Content(mediaType = "application/json", schema = @Schema(implementation = Prompt.class)), responseCode = "200", description = "Class generated successfully")
  public void generateClass(Prompt prompt, @Parameter(hidden = true) ServerResponse res) {
    var chat = dbService.getChatById(prompt.chatId());
    var newLLM = dbService.getLLMById(chat.llmId());
    dbService.insertPrompt(prompt);

    ClassResponse generatedClass;
    try {
      generatedClass = generateClassFromLLM(newLLM, chat.id(), prompt.message());
      LOGGER.info("Class generated successfully.");
    } catch (IOException | InterruptedException | ExecutionException e) { // Catch is necessary because whe are in a BiConsumer lambda
      throw new RestApiException(e);
    }

    // There generatedClass is never null, the generateClassFromLLM method throws an exception
    var aiPrompt = new Prompt(0, generatedClass.code(), AuthorType.AI, chat.id(), generatedClass.compile());
    dbService.insertPrompt(aiPrompt);
    var realPrompt = dbService.getPromptByPromptInfo(aiPrompt);
    res.status(Status.OK_200).send(realPrompt);
  }

  @POST
  @javax.ws.rs.Path("/exec")
  @Operation(summary = "Execute a class", description = "Executes a java class and returns the output")
  @Consumes("text/plain")
  @ApiResponse(content = @Content(mediaType = "text/plain"), responseCode = "200", description = "Class execution output")
  public void executeClass(int promptId, @Parameter(hidden = true) ServerResponse res) {
    var prompt = dbService.getPromptById(promptId);
    if (!prompt.compile()) {
      ErrorUtils.send(res, Status.NOT_ACCEPTABLE_406, "Prompt not supposed to be compiled.");
      return;
    }

    String output;
    try {
      LOGGER.info("Executing class, promptId : {}", promptId);
      output = CompileAndExecUtils.processText(prompt.message(), CompileAndExecUtils.Operation.EXECUTE);
    } catch (IOException | InterruptedException | ExecutionException e) { // Catch is necessary because whe are in a BiConsumer lambda
      throw new RestApiException(e);
    }
    res.status(Status.OK_200).send(output);
  }

  private ClassResponse generateClassFromLLM(LLM llm, int chatId, String requestText)
          throws IOException, InterruptedException, ExecutionException {
    Objects.requireNonNull(llm);
    Objects.requireNonNull(requestText);

    if (llm != curLLM || model == null || assistant == null) {
      updateModelSettings(llm, chatId);
      curLLM = llm;
    }

    String errorsText = null;
    String code = null;
    for (int attempt = 1; attempt <= NB_ATTEMPTS; attempt++) {
      LOGGER.info("Attempting to generate a class : {}/{}", attempt, NB_ATTEMPTS);

      var stream = assistant.chat(attempt == 1 ? requestText : errorsText);
      var aiAnswer = new AiAnswer();
      stream.onNext(System.out::println)
              .onComplete(res -> aiAnswer.setAnswer(res.content().text()))
              .onError(Throwable::printStackTrace)
              .start();
      LOGGER.info("Assistant made a response.");

      code = CompileAndExecUtils.extractCode(aiAnswer.getAnswer());
      LOGGER.info("Code extracted from response.");

      var errors = CompileAndExecUtils.processText(code, CompileAndExecUtils.Operation.COMPILE);

      if (errors.isEmpty()) {
        LOGGER.info("No errors found in generated code.");
        return new ClassResponse(code, true);
      } else {
        LOGGER.error("Errors found in generated code.");
        errorsText = SYSTEM_ERR_MESSAGE + errors;
      }
    }
    return new ClassResponse(code, false);
  }

  private interface Assistant {
    TokenStream chat(@UserMessage String userMessage);
  }

  // Added this class to manipulate the response of llm when the stream is completed
  private static class AiAnswer {
    private String answer = "";
    String getAnswer() {
      return answer;
    }
    void setAnswer(String answer) {
      Objects.requireNonNull(answer);
      this.answer = answer;
    }
  }

  private void updateModelSettings(LLM llm, int chatId) {
    var chatMemory = MessageWindowChatMemory.withMaxMessages(MAX_MEMORY_PROMPTS);
    updateMemoryWithPreviousPrompts(chatMemory, chatId);
//    model = OllamaChatModel.builder()
    model = OllamaStreamingChatModel.builder()
            .baseUrl(llmConfig.baseUrl())
            .modelName(llm.model())
            .temperature(llm.temp())
            .seed(llm.seed())
            .build();

    assistant = AiServices.builder(Assistant.class)
//            .chatLanguageModel(model)
            .streamingChatLanguageModel(model)
            .systemMessageProvider(_ -> llm.systemPrompt())
            .chatMemory(chatMemory)
            .build();
  }

  private void updateMemoryWithPreviousPrompts(ChatMemory chatMemory, int chatId) {
    var prevPrompts = dbService.getPromptsByChatId(chatId);
    prevPrompts.stream()
            .filter(prompt -> prompt.authorType() != AuthorType.SYSTEM)
            .forEach(prompt -> chatMemory.add(new ChatMessage() {
                @Override
                public ChatMessageType type() {
                  return ChatMessageType.valueOf(prompt.authorType().name());
                }

                @Override
                public String text() {
                  return prompt.message();
                }
              }));
  }
}
